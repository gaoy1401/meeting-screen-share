#!/usr/bin/env bash
set -euo pipefail

if [[ $(id -u) -ne 0 ]]; then
    echo "install-public-server.sh must run as root" >&2
    exit 1
fi

PUBLIC_IP=${PUBLIC_IP:?PUBLIC_IP is required}
STAGE_DIR=${STAGE_DIR:-/tmp/meeting-public-deploy}
MEETING_ROOT=/opt/meeting
CONFIG_ROOT=/etc/meeting
SERVICE_USER=meeting

[[ "$PUBLIC_IP" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]] || {
    echo "PUBLIC_IP must be an IPv4 address" >&2; exit 2;
}
# Check prerequisites before changing services or installing packages.
command -v nginx >/dev/null || { echo "Install and configure nginx first" >&2; exit 1; }
command -v node >/dev/null || { echo "Install Node.js 22+ first" >&2; exit 1; }
command -v npm >/dev/null || { echo "Install npm first" >&2; exit 1; }
(( $(node -p 'Number(process.versions.node.split(".")[0])') >= 22 )) || {
    echo "Node.js 22+ is required" >&2; exit 1;
}
for cert in fullchain.pem privkey.pem; do
    [[ -s "/etc/letsencrypt/live/$PUBLIC_IP/$cert" ]] || {
        echo "Missing trusted TLS certificate: /etc/letsencrypt/live/$PUBLIC_IP/$cert" >&2
        exit 1
    }
done

require_file() {
    if [[ ! -f $1 ]]; then
        echo "missing deployment file: $1" >&2
        exit 1
    fi
}

for file in \
    "$STAGE_DIR/server/package.json" \
    "$STAGE_DIR/server/package-lock.json" \
    "$STAGE_DIR/public/livekit-public.yaml.template" \
    "$STAGE_DIR/public/meeting-livekit-nginx.conf.template" \
    "$STAGE_DIR/public/meeting-livekit-public.service" \
    "$STAGE_DIR/public/meeting-control-public.service"; do
    require_file "$file"
done

export DEBIAN_FRONTEND=noninteractive
apt-get update
apt-get install -y ca-certificates curl openssl rsync

if ! id "$SERVICE_USER" >/dev/null 2>&1; then
    useradd --system --home-dir "$MEETING_ROOT" --shell /usr/sbin/nologin "$SERVICE_USER"
fi

install -d -o "$SERVICE_USER" -g "$SERVICE_USER" -m 0750 "$MEETING_ROOT"
install -d -o "$SERVICE_USER" -g "$SERVICE_USER" -m 0750 "$MEETING_ROOT/server"
install -d -o root -g "$SERVICE_USER" -m 0750 "$CONFIG_ROOT"

rsync -a --delete \
    --exclude node_modules \
    "$STAGE_DIR/server/" "$MEETING_ROOT/server/"
chown -R "$SERVICE_USER:$SERVICE_USER" "$MEETING_ROOT/server"

runuser -u "$SERVICE_USER" -- \
    npm --prefix "$MEETING_ROOT/server" ci --omit=dev --no-audit --no-fund

if ! command -v livekit-server >/dev/null 2>&1; then
    installer=$(mktemp)
    curl -fsSL https://get.livekit.io -o "$installer"
    if ! grep -q 'REPO="livekit"' "$installer"; then
        echo "unexpected LiveKit installer content" >&2
        rm -f "$installer"
        exit 1
    fi
    bash "$installer"
    rm -f "$installer"
fi

credentials_file="$CONFIG_ROOT/credentials.env"
if [[ ! -s $credentials_file ]]; then
    umask 077
    api_key="meeting_$(openssl rand -hex 12)"
    api_secret=$(openssl rand -hex 32)
    {
        printf 'MEETING_LIVEKIT_API_KEY=%s\n' "$api_key"
        printf 'MEETING_LIVEKIT_API_SECRET=%s\n' "$api_secret"
    } >"$credentials_file"
fi

# The file is generated by this installer from hex-only values.
# shellcheck disable=SC1090
source "$credentials_file"

rendered_livekit=$(mktemp)
sed \
    -e "s/__PUBLIC_IP__/$PUBLIC_IP/g" \
    -e "s/__API_KEY__/$MEETING_LIVEKIT_API_KEY/g" \
    -e "s/__API_SECRET__/$MEETING_LIVEKIT_API_SECRET/g" \
    "$STAGE_DIR/public/livekit-public.yaml.template" >"$rendered_livekit"
install -o root -g "$SERVICE_USER" -m 0640 \
    "$rendered_livekit" "$CONFIG_ROOT/livekit.yaml"
rm -f "$rendered_livekit"

control_env=$(mktemp)
{
    printf 'MEETING_HOST=127.0.0.1\n'
    printf 'MEETING_PORT=9000\n'
    printf 'MEETING_MAX_PARTICIPANTS=8\n'
    printf 'MEETING_MEMBER_TIMEOUT_MS=15000\n'
    printf 'MEETING_LIVEKIT_URL=wss://%s:7880\n' "$PUBLIC_IP"
    printf 'MEETING_LIVEKIT_API_KEY=%s\n' "$MEETING_LIVEKIT_API_KEY"
    printf 'MEETING_LIVEKIT_API_SECRET=%s\n' "$MEETING_LIVEKIT_API_SECRET"
    printf 'MEETING_LIVEKIT_TOKEN_TTL_SECONDS=600\n'
} >"$control_env"
install -o root -g "$SERVICE_USER" -m 0640 \
    "$control_env" "$CONFIG_ROOT/control.env"
rm -f "$control_env"
chmod 0600 "$credentials_file"

nginx_rendered=$(mktemp)
sed "s/__PUBLIC_IP__/$PUBLIC_IP/g" \
    "$STAGE_DIR/public/meeting-livekit-nginx.conf.template" >"$nginx_rendered"
nginx_target=/etc/nginx/conf.d/meeting-livekit.conf
nginx_backup=
if [[ -f $nginx_target ]]; then
    nginx_backup=$(mktemp)
    cp "$nginx_target" "$nginx_backup"
fi
install -o root -g root -m 0644 "$nginx_rendered" "$nginx_target"
rm -f "$nginx_rendered"
if ! nginx -t; then
    if [[ -n $nginx_backup ]]; then
        cp "$nginx_backup" "$nginx_target"
    else
        rm -f "$nginx_target"
    fi
    rm -f "$nginx_backup"
    exit 1
fi
rm -f "$nginx_backup"
systemctl reload nginx

udp_sysctl=$(mktemp)
{
    printf 'net.core.rmem_max=5000000\n'
    printf 'net.core.wmem_max=5000000\n'
} >"$udp_sysctl"
install -o root -g root -m 0644 \
    "$udp_sysctl" /etc/sysctl.d/99-meeting-livekit.conf
rm -f "$udp_sysctl"
sysctl -q -w net.core.rmem_max=5000000
sysctl -q -w net.core.wmem_max=5000000

install -o root -g root -m 0644 \
    "$STAGE_DIR/public/meeting-livekit-public.service" \
    /etc/systemd/system/meeting-livekit-public.service
install -o root -g root -m 0644 \
    "$STAGE_DIR/public/meeting-control-public.service" \
    /etc/systemd/system/meeting-control-public.service

systemctl daemon-reload
systemctl enable meeting-livekit-public.service
systemctl enable meeting-control-public.service
systemctl restart meeting-livekit-public.service
systemctl restart meeting-control-public.service

services_ready=0
for _ in {1..30}; do
    if curl -fsS http://127.0.0.1:7883/ >/dev/null 2>&1 &&
        node "$MEETING_ROOT/server/tools/check-webrtc-server.js" \
            127.0.0.1 9000 >/dev/null 2>&1; then
        services_ready=1
        break
    fi
    sleep 0.5
done

if [[ $services_ready -ne 1 ]]; then
    systemctl --no-pager --full status \
        meeting-livekit-public.service meeting-control-public.service || true
    journalctl -u meeting-livekit-public.service \
        -u meeting-control-public.service -n 100 --no-pager
    exit 1
fi

systemctl --no-pager --full status meeting-livekit-public.service
systemctl --no-pager --full status meeting-control-public.service
node "$MEETING_ROOT/server/tools/check-webrtc-server.js" 127.0.0.1 9000
livekit-server --version
