#!/bin/zsh
set -euo pipefail

ROOT_DIR=${0:A:h:h:h}
source "$ROOT_DIR/mac-server/lib/common.sh"

require_macos
require_command livekit-server
require_command node
require_command npm
require_command lsof
require_command launchctl
ensure_runtime_dirs

if launchd_service_is_loaded "$LIVEKIT_LABEL" &&
   launchd_service_is_loaded "$CONTROL_LABEL"; then
  print -- "Mac 会议服务器已经在运行。"
  exec "$ROOT_DIR/mac-server/bin/status.sh"
fi
if launchd_service_is_loaded "$LIVEKIT_LABEL" ||
   launchd_service_is_loaded "$CONTROL_LABEL"; then
  launchctl bootout "$LAUNCHD_DOMAIN/$CONTROL_LABEL" >/dev/null 2>&1 || true
  launchctl bootout "$LAUNCHD_DOMAIN/$LIVEKIT_LABEL" >/dev/null 2>&1 || true
fi

for endpoint in TCP:7880 TCP:7881 TCP:9000 UDP:7882 UDP:9000; do
  protocol="${endpoint%%:*}"
  port="${endpoint##*:}"
  if /usr/sbin/lsof -nP "-i${protocol}:$port" 2>/dev/null |
     grep -q .; then
    /usr/sbin/lsof -nP "-i${protocol}:$port" >&2 || true
    die "$port/$protocol 已被其他进程占用。"
  fi
done

if [[ ! -d "$ROOT_DIR/server/node_modules/livekit-server-sdk" ]]; then
  die "Node 依赖尚未安装。请先运行 mac-server/bin/install.sh。"
fi

server_ip="$(detect_lan_ip)"
ensure_credentials
load_credentials

cat >"$LIVEKIT_CONFIG" <<EOF
# Generated by mac-server/bin/start.sh for trusted LAN testing.
port: 7880
rtc:
  tcp_port: 7881
  udp_port: 7882
  use_external_ip: false
  node_ip: $server_ip
keys:
  $MEETING_LIVEKIT_API_KEY: $MEETING_LIVEKIT_API_SECRET
logging:
  level: info
EOF
chmod 600 "$LIVEKIT_CONFIG"

cat >"$STATE_FILE" <<EOF
MEETING_MAC_SERVER_IP=$server_ip
MEETING_CONTROL_ENDPOINT=$server_ip:9000
MEETING_LIVEKIT_URL=ws://$server_ip:7880
EOF
chmod 600 "$STATE_FILE"

: >"$LIVEKIT_LOG"
: >"$LIVEKIT_ERROR_LOG"
: >"$CONTROL_LOG"
: >"$CONTROL_ERROR_LOG"

livekit_binary="$(command -v livekit-server)"
node_binary="$(command -v node)"

escaped_livekit_binary="$(xml_escape "$livekit_binary")"
escaped_livekit_config="$(xml_escape "$LIVEKIT_CONFIG")"
escaped_root_dir="$(xml_escape "$ROOT_DIR")"
escaped_livekit_log="$(xml_escape "$LIVEKIT_LOG")"
escaped_livekit_error_log="$(xml_escape "$LIVEKIT_ERROR_LOG")"
escaped_node_binary="$(xml_escape "$node_binary")"
escaped_control_log="$(xml_escape "$CONTROL_LOG")"
escaped_control_error_log="$(xml_escape "$CONTROL_ERROR_LOG")"
escaped_server_ip="$(xml_escape "$server_ip")"
escaped_api_key="$(xml_escape "$MEETING_LIVEKIT_API_KEY")"
escaped_api_secret="$(xml_escape "$MEETING_LIVEKIT_API_SECRET")"

cat >"$LIVEKIT_PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>$LIVEKIT_LABEL</string>
  <key>ProgramArguments</key>
  <array>
    <string>$escaped_livekit_binary</string>
    <string>--config</string>
    <string>$escaped_livekit_config</string>
  </array>
  <key>WorkingDirectory</key>
  <string>$escaped_root_dir</string>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <true/>
  <key>ThrottleInterval</key>
  <integer>2</integer>
  <key>StandardOutPath</key>
  <string>$escaped_livekit_log</string>
  <key>StandardErrorPath</key>
  <string>$escaped_livekit_error_log</string>
</dict>
</plist>
EOF

cat >"$CONTROL_PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>$CONTROL_LABEL</string>
  <key>ProgramArguments</key>
  <array>
    <string>$escaped_node_binary</string>
    <string>src/index.js</string>
  </array>
  <key>WorkingDirectory</key>
  <string>$escaped_root_dir/server</string>
  <key>EnvironmentVariables</key>
  <dict>
    <key>MEETING_HOST</key>
    <string>0.0.0.0</string>
    <key>MEETING_PORT</key>
    <string>9000</string>
    <key>MEETING_LIVEKIT_URL</key>
    <string>ws://$escaped_server_ip:7880</string>
    <key>MEETING_LIVEKIT_API_KEY</key>
    <string>$escaped_api_key</string>
    <key>MEETING_LIVEKIT_API_SECRET</key>
    <string>$escaped_api_secret</string>
  </dict>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <true/>
  <key>ThrottleInterval</key>
  <integer>2</integer>
  <key>StandardOutPath</key>
  <string>$escaped_control_log</string>
  <key>StandardErrorPath</key>
  <string>$escaped_control_error_log</string>
</dict>
</plist>
EOF
chmod 600 "$LIVEKIT_PLIST" "$CONTROL_PLIST"
plutil -lint "$LIVEKIT_PLIST" "$CONTROL_PLIST" >/dev/null

print -- "正在启动 LiveKit SFU..."
launchctl bootstrap "$LAUNCHD_DOMAIN" "$LIVEKIT_PLIST"

if ! wait_for_tcp 127.0.0.1 7880; then
  show_log_tail "LiveKit" "$LIVEKIT_LOG"
  show_log_tail "LiveKit 错误" "$LIVEKIT_ERROR_LOG"
  "$ROOT_DIR/mac-server/bin/stop.sh" >/dev/null 2>&1 || true
  die "LiveKit 没有在 7880/TCP 就绪。"
fi

print -- "正在启动 TCP 控制和令牌服务..."
launchctl bootstrap "$LAUNCHD_DOMAIN" "$CONTROL_PLIST"

if ! wait_for_tcp 127.0.0.1 9000; then
  show_log_tail "控制服务" "$CONTROL_LOG"
  show_log_tail "控制服务错误" "$CONTROL_ERROR_LOG"
  "$ROOT_DIR/mac-server/bin/stop.sh" >/dev/null 2>&1 || true
  die "控制服务没有在 9000/TCP 就绪。"
fi

if ! node "$ROOT_DIR/server/tools/check-webrtc-server.js" "$server_ip" 9000; then
  show_log_tail "LiveKit" "$LIVEKIT_LOG"
  show_log_tail "LiveKit 错误" "$LIVEKIT_ERROR_LOG"
  show_log_tail "控制服务" "$CONTROL_LOG"
  show_log_tail "控制服务错误" "$CONTROL_ERROR_LOG"
  "$ROOT_DIR/mac-server/bin/stop.sh" >/dev/null 2>&1 || true
  die "Mac 服务器自检失败。"
fi

print -- ""
print -- "Mac 会议服务器启动成功。"
print -- "同一台 Mac 客户端：127.0.0.1:9000"
print -- "局域网其他客户端：$server_ip:9000"
print -- "房间号：demo"
print -- "日志目录：$LOG_DIR"
print -- ""
print -- "首次运行如果 macOS 弹出网络访问提示，请允许 node 和 livekit-server 接收入站连接。"
